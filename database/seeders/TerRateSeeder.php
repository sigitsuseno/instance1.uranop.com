    /**
     * Label resmi kategori TER.
     */
    private const CATEGORY_LABELS = [
        'A' => 'TK/0, TK/1, K/0',
        'B' => 'TK/2, TK/3, K/1, K/2',
        'C' => 'K/3',
    ];

    /** @var int Default user ID pembuat record (admin pertama). */
    private const DEFAULT_USER_ID = 1;

    public function run(): void
    {
        // ── 1. Pastikan pph_config aktif ada ──
        $config = PphConfig::where('is_active', true)->first();

        if (! $config) {
            $config = PphConfig::create([
                'uuid'                 => (string) Str::uuid(),
                'effective_date'       => '2024-01-01',
                'is_active'            => true,
                'calculation_method'   => 'ter',
                'pph_method'           => 'gross',
                'non_npwp_penalty'     => true,
                'non_npwp_multiplier'  => 1.20,
                'description'          => 'Konfigurasi PPh 21 Standar Indonesia (PP 58/2023 TER & UU HPP) — auto-generated oleh TerRateSeeder',
                'created_by'           => self::DEFAULT_USER_ID,
            ]);

            $this->command->info("ℹ️  pph_configs (id={$config->id}) dibuat otomatis.");
        }

        $configId = $config->id;

        // ── 2. Hapus TER rates existing untuk konfigurasi ini (idempoten) ──
        $deleted = TerRate::where('pph_config_id', $configId)->delete();
        if ($deleted > 0) {
            $this->command->info("🧹 {$deleted} TER rate(s) lama dihapus.");
        }

        // ── 3. Insert TER rates PP 58/2023 ──
        $totalInserted = 0;

        foreach (['A', 'B', 'C'] as $category) {
            $sortOrder = 0;

            foreach (self::TER_RATES[$category] as $bracket) {
                TerRate::create([
                    'pph_config_id' => $configId,
                    'category'      => $category,
                    'min_income'    => $bracket[0],
                    'max_income'    => $bracket[1],
                    'rate'          => $bracket[2],
                    'description'   => self::CATEGORY_LABELS[$category],
                    'sort_order'    => ++$sortOrder,
                    'created_by'    => self::DEFAULT_USER_ID,
                ]);

                $totalInserted++;
            }
        }

        $this->command->info(
            "✅ TER Rate seeder selesai — {$totalInserted} bracket " .
            '(A=' . count(self::TER_RATES['A']) .
            ', B=' . count(self::TER_RATES['B']) .
            ', C=' . count(self::TER_RATES['C']) . ') ' .
            "untuk pph_config_id={$configId}"
        );

        $this->command->info('📋 Halaman: /admin/payroll/pph → tab "TER Bulanan"');
    }
